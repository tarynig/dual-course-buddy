CREATE TABLE public.applications (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  course_id text REFERENCES public.courses(id),
  dual_course_id text REFERENCES public.dual_courses(id),
  item_name text,
  first_name text NOT NULL,
  last_name text NOT NULL,
  id_number text NOT NULL,
  date_of_birth date NOT NULL,
  gender text NOT NULL,
  home_language text NOT NULL,
  location text NOT NULL,
  email text NOT NULL,
  cell text NOT NULL,
  last_school text NOT NULL,
  highest_grade text NOT NULL,
  grade_year integer NOT NULL,
  current_grade text,
  studied_elsewhere boolean NOT NULL DEFAULT false,
  institution_name text,
  institution_qualification text,
  institution_completed boolean,
  payer_first_name text NOT NULL,
  payer_last_name text NOT NULL,
  payer_phone text NOT NULL,
  payer_email text NOT NULL,
  payer_id_number text NOT NULL,
  payer_relationship text NOT NULL,
  payer_address text NOT NULL,
  payer_employment text NOT NULL,
  status text NOT NULL DEFAULT 'new',
  created_at timestamptz NOT NULL DEFAULT now()
);
GRANT ALL ON public.applications TO service_role;
ALTER TABLE public.applications ENABLE ROW LEVEL SECURITY;